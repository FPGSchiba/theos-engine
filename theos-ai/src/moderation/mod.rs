//! Content moderation: the categories a game can react to, the trait a game
//! implements, and a pipeline that runs several moderators in order.

use crate::embed::EmbedError;

mod knn;

pub use knn::{
    KnnEvidence, KnnModerator, KnnThresholds, MIN_PIECE_WORDS, Nearest, SourceThreshold,
    moderation_pieces,
};

/// A kind of content a game can react to.
#[derive(Clone, Debug, PartialEq, Eq, Hash)]
#[non_exhaustive]
pub enum ModerationCategory {
    /// Encouragement or instructions for self-harm.
    SelfHarm,
    /// Hateful content.
    Hate,
    /// Instructions for harming people in the real world.
    RealWorldHarm,
    /// Sexual content involving minors.
    SexualMinors,
    /// Content that breaks the fiction of the game world.
    WorldBreak,
    /// A game-defined category, identified by its own string.
    Custom(String),
}

impl ModerationCategory {
    /// The stable id used in configuration and tables.
    pub fn id(&self) -> &str {
        match self {
            Self::SelfHarm => "self-harm",
            Self::Hate => "hate",
            Self::RealWorldHarm => "real-world-harm",
            Self::SexualMinors => "sexual-minors",
            Self::WorldBreak => "world-break",
            Self::Custom(id) => id,
        }
    }

    /// The category for an id; an unknown id becomes [`ModerationCategory::Custom`].
    pub fn from_id(id: &str) -> Self {
        match id {
            "self-harm" => Self::SelfHarm,
            "hate" => Self::Hate,
            "real-world-harm" => Self::RealWorldHarm,
            "sexual-minors" => Self::SexualMinors,
            "world-break" => Self::WorldBreak,
            other => Self::Custom(other.to_owned()),
        }
    }
}

/// Where the checked text came from.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum ModerationSource {
    /// A message typed by the player.
    PlayerMessage,
    /// A reply generated by the model.
    ModelReply,
}

/// The outcome of checking one text.
#[derive(Clone, Debug, PartialEq, Eq)]
pub enum ModerationVerdict {
    /// The text may pass.
    Allow,
    /// The text is blocked for the given category.
    Block(ModerationCategory),
}

/// Why a moderator could not reach a verdict.
#[derive(Clone, Debug, PartialEq, Eq, thiserror::Error)]
#[non_exhaustive]
pub enum ModerationError {
    /// Embedding the text failed.
    #[error(transparent)]
    Embed(#[from] EmbedError),
    /// The moderator failed for another reason.
    #[error("moderation failed: {0}")]
    Failed(String),
}

/// Decides whether a text may pass.
///
/// Takes `&mut self` and has no `Send` bound: the NPC worker builds its parts
/// on its own thread.
pub trait ContentModerator {
    /// Checks `text`, which came from `source`.
    ///
    /// # Errors
    /// Returns a [`ModerationError`] when no verdict can be reached; callers
    /// must treat that as a block (fail closed).
    fn check(
        &mut self,
        source: ModerationSource,
        text: &str,
    ) -> Result<ModerationVerdict, ModerationError>;
}

/// A moderator that allows everything.
#[derive(Clone, Copy, Debug, Default)]
pub struct AllowAll;

impl ContentModerator for AllowAll {
    fn check(
        &mut self,
        _source: ModerationSource,
        _text: &str,
    ) -> Result<ModerationVerdict, ModerationError> {
        Ok(ModerationVerdict::Allow)
    }
}

/// Runs several moderators in order.
///
/// The first block is returned and later stages do not run. The first error is
/// returned (fail closed) and later stages do not run. An empty pipeline
/// allows everything.
pub struct ModerationPipeline {
    stages: Vec<Box<dyn ContentModerator>>,
}

impl ModerationPipeline {
    /// A pipeline running `stages` in order.
    pub fn new(stages: Vec<Box<dyn ContentModerator>>) -> Self {
        Self { stages }
    }
}

impl ContentModerator for ModerationPipeline {
    fn check(
        &mut self,
        source: ModerationSource,
        text: &str,
    ) -> Result<ModerationVerdict, ModerationError> {
        for stage in &mut self.stages {
            if let block @ ModerationVerdict::Block(_) = stage.check(source, text)? {
                return Ok(block);
            }
        }
        Ok(ModerationVerdict::Allow)
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    use std::cell::Cell;
    use std::rc::Rc;

    struct Stub {
        result: Result<ModerationVerdict, ModerationError>,
        calls: Rc<Cell<usize>>,
    }

    impl ContentModerator for Stub {
        fn check(
            &mut self,
            _source: ModerationSource,
            _text: &str,
        ) -> Result<ModerationVerdict, ModerationError> {
            self.calls.set(self.calls.get() + 1);
            self.result.clone()
        }
    }

    fn stub(
        result: Result<ModerationVerdict, ModerationError>,
    ) -> (Box<dyn ContentModerator>, Rc<Cell<usize>>) {
        let calls = Rc::new(Cell::new(0));
        (
            Box::new(Stub {
                result,
                calls: calls.clone(),
            }),
            calls,
        )
    }

    #[test]
    fn category_ids_round_trip_and_unknown_is_custom() {
        for (cat, id) in [
            (ModerationCategory::SelfHarm, "self-harm"),
            (ModerationCategory::Hate, "hate"),
            (ModerationCategory::RealWorldHarm, "real-world-harm"),
            (ModerationCategory::SexualMinors, "sexual-minors"),
            (ModerationCategory::WorldBreak, "world-break"),
        ] {
            assert_eq!(cat.id(), id);
            assert_eq!(ModerationCategory::from_id(id), cat);
        }
        let custom = ModerationCategory::from_id("spoilers");
        assert_eq!(custom, ModerationCategory::Custom("spoilers".to_owned()));
        assert_eq!(custom.id(), "spoilers");
    }

    #[test]
    fn allow_all_allows() {
        let v = AllowAll.check(ModerationSource::PlayerMessage, "anything");
        assert_eq!(v, Ok(ModerationVerdict::Allow));
    }

    #[test]
    fn pipeline_returns_the_first_block_and_skips_later_stages() {
        let (a, a_calls) = stub(Ok(ModerationVerdict::Allow));
        let (b, b_calls) = stub(Ok(ModerationVerdict::Block(ModerationCategory::Hate)));
        let (c, c_calls) = stub(Ok(ModerationVerdict::Block(ModerationCategory::WorldBreak)));
        let mut p = ModerationPipeline::new(vec![a, b, c]);
        let v = p.check(ModerationSource::ModelReply, "x");
        assert_eq!(v, Ok(ModerationVerdict::Block(ModerationCategory::Hate)));
        assert_eq!((a_calls.get(), b_calls.get(), c_calls.get()), (1, 1, 0));
    }

    #[test]
    fn pipeline_error_fails_closed_even_if_a_later_stage_would_allow() {
        let (a, _) = stub(Err(ModerationError::Failed("boom".to_owned())));
        let (b, b_calls) = stub(Ok(ModerationVerdict::Allow));
        let mut p = ModerationPipeline::new(vec![a, b]);
        let v = p.check(ModerationSource::PlayerMessage, "x");
        assert_eq!(v, Err(ModerationError::Failed("boom".to_owned())));
        assert_eq!(b_calls.get(), 0);
    }

    #[test]
    fn empty_pipeline_allows() {
        let mut p = ModerationPipeline::new(Vec::new());
        assert_eq!(
            p.check(ModerationSource::PlayerMessage, "x"),
            Ok(ModerationVerdict::Allow)
        );
    }

    #[test]
    fn embed_error_converts_and_displays() {
        let e: ModerationError = crate::EmbedError::Backend("x".to_owned()).into();
        assert!(matches!(e, ModerationError::Embed(_)));
        assert!(e.to_string().contains("embedding"));
    }
}
